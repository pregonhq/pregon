-- Segments and their transcription queue (ADR-0024, ADR-0025 §8 and §9).
--
-- Two tables, two lifetimes: `segment` keeps the metadata for the retention period, partitioned by
-- month so that old metadata is dropped, not deleted; `segment_audio` holds the bytes only until the
-- segment is transcribed or fails. The queue state lives in `segment` itself.

-- The composite foreign key below needs this; a segment can only name a source of its own tenant,
-- even if application code is wrong.
ALTER TABLE source ADD CONSTRAINT source_tenant_id_id_key UNIQUE (tenant_id, id);

CREATE TABLE segment (
    tenant_id            text        NOT NULL REFERENCES tenant (id) ON DELETE RESTRICT,
    -- UUIDv7 generated by the agent (ADR-0022): the idempotency key, and a timestamp in its high
    -- 48 bits, which is what makes a range of ids a range of time.
    id                   uuid        NOT NULL,
    source_id            uuid        NOT NULL,
    capture_start        timestamptz NOT NULL,
    capture_end          timestamptz NOT NULL,
    -- Stored parsed (ADR-0025 §5): comparing columns is comparing by value.
    voiced_millis        bigint      NOT NULL CHECK (voiced_millis > 0),
    agent_version        text        CHECK (length(agent_version) <= 40),
    audio_sha256         bytea       NOT NULL CHECK (octet_length(audio_sha256) = 32),
    audio_bytes          integer     NOT NULL CHECK (audio_bytes > 0),
    received_at          timestamptz NOT NULL,
    clock_skew_suspected boolean     NOT NULL,
    -- Queue (ADR-0025 §9): the attempt is counted when the job is claimed and is the lease token.
    state                text        NOT NULL DEFAULT 'QUEUED' CHECK (state IN ('QUEUED', 'LEASED', 'TRANSCRIBED', 'FAILED')),
    attempt              integer     NOT NULL DEFAULT 0,
    lease_until          timestamptz,
    failure_reason       text,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, source_id) REFERENCES source (tenant_id, id) ON DELETE RESTRICT,
    CHECK (capture_end > capture_start)
) PARTITION BY RANGE (id);

-- The queue's working set: small, cached, in capture order. Also what `complete` and `fail` hit.
CREATE INDEX segment_queue_idx ON segment (id) WHERE state IN ('QUEUED', 'LEASED');

-- Quotas per tenant and per source are a sum over the same working set (ADR-0025 §7).
CREATE INDEX segment_quota_idx ON segment (tenant_id, source_id) INCLUDE (audio_bytes) WHERE state IN ('QUEUED', 'LEASED');

-- Safety net: a month without its partition, or an agent whose clock produces an absurd id, lands
-- here instead of failing. Rows in it are an operational signal, not an error.
CREATE TABLE segment_default PARTITION OF segment DEFAULT;

-- Partitions for the current month and the next two, so ingestion does not stop at midnight on the
-- first. The server repeats this at startup and daily (SegmentPartitions), with the same names and
-- bounds; both use IF NOT EXISTS, so they never disagree.
DO $$
DECLARE
    month_start timestamptz;
    lower_ms    bigint;
    upper_ms    bigint;
BEGIN
    FOR offset_months IN 0..2 LOOP
        month_start := date_trunc('month', now() AT TIME ZONE 'UTC') + make_interval(months => offset_months);
        lower_ms := floor(extract(epoch FROM month_start) * 1000);
        upper_ms := floor(extract(epoch FROM (month_start + interval '1 month')) * 1000);
        -- The 48-bit timestamp fills the first 8-4 groups of the uuid; every other bit is zero.
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF segment FOR VALUES FROM (%L) TO (%L)',
            'segment_' || to_char(month_start, 'YYYY_MM'),
            regexp_replace(lpad(to_hex(lower_ms), 12, '0'), '^(.{8})(.{4})$', '\1-\2') || '-0000-0000-000000000000',
            regexp_replace(lpad(to_hex(upper_ms), 12, '0'), '^(.{8})(.{4})$', '\1-\2') || '-0000-0000-000000000000');
    END LOOP;
END $$;

CREATE TABLE segment_audio (
    tenant_id  text  NOT NULL,
    segment_id uuid  NOT NULL,
    bytes      bytea NOT NULL,
    PRIMARY KEY (tenant_id, segment_id)
);

-- Opus is already compressed: TOAST must not spend CPU trying again (ADR-0025 §8).
ALTER TABLE segment_audio ALTER COLUMN bytes SET STORAGE EXTERNAL;

-- Rows live minutes; without this, dead tuples would pile up between the default vacuum runs.
ALTER TABLE segment_audio SET (autovacuum_vacuum_scale_factor = 0.01, autovacuum_vacuum_cost_delay = 0);
